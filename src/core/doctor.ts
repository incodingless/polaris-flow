/**
 * doctor 诊断：Node/命令可用性、依赖登记表逐条状态、安装状态记录与平台 polaris 安装状态。
 *
 * 依赖检查消费 `deps/registry.ts` 的 probe 声明，与 init 的判定同源：
 * 用 `isCommandAvailable` 只看 PATH 会漏掉 init 装到 `~/.polaris/cli/bin` 的 CLI
 * （全局 npm 目录不可写时的落点），从而把已装的组件误报成缺失。
 */
import { createRequire } from 'module';

import { fileExists } from '../utils/file-system.js';
import { readJsonObjectOrEmpty } from '../utils/json-io.js';
import { isCommandAvailable } from './integrations/openspec.js';
import { getBundledSkillsSourceDir } from './integrations/bundled-skills.js';
import { detectPlatforms, getBaseDir, hasSkills, readCliVersion } from './integrations/detect.js';
import { probeDependency } from './deps/probe.js';
import { DEPENDENCIES, type DependencyRequiredness, type LocalFallback } from './deps/registry.js';
import { resolveCliExecutable } from './deps/npm.js';
import { compareVersions, extractSemver } from './deps/version.js';
import { isConcreteVersion } from './update/dep-version.js';
import { getInstallStatePath, readInstallState } from './install/install-state.js';
import { PLATFORMS, getPlatformSkillsDir } from './domain/platforms.js';
import type { InstallScope } from './config/polaris-project-config.js';
import type { Languages } from './config/polaris-project-config.js';

const require = createRequire(import.meta.url);
const { engines } = require('../../package.json') as { engines?: { node?: string } };

/** 本程序能读懂的 install-state 格式版本；文件里更大说明记录由更新的 polaris 生成 */
const INSTALL_STATE_FORMAT_VERSION = 1;

/**
 * doctor 文案表（en / zh 双语）。
 *
 * 放在 core 而非 `commands/i18n/messages.yaml`：依赖方向 `commands → core` 禁止反向，
 * core 不能 import `t()`；而诊断消息由 core 的判定逻辑逐条构造，键表随判定走同一文件，
 * 避免「改了判定忘了改文案」。dashboard 不 import commands，也能用同一份表按语言输出。
 */
const MESSAGES = {
  nodeRequires: { en: '{version} (requires >= {min})', zh: '{version}（要求 >= {min}）' },
  commandAvailable: { en: 'available', zh: '可用' },
  commandNotFound: { en: 'not found in PATH', zh: '未在 PATH 中找到' },
  requiredLabel: { en: 'required', zh: '必需' },
  recommendedLabel: { en: 'recommended', zh: '推荐' },
  optionalLabel: { en: 'optional', zh: '可选' },
  depInstalled: { en: 'installed ({label})', zh: '已安装（{label}）' },
  depMissing: { en: 'not installed ({label})', zh: '未安装（{label}）' },
  depMissingNoBlock: { en: ', does not block the workflow', zh: '，不影响工作流' },
  depHintReinstall: {
    en: 'Re-run polaris init; for offline environments set install.local-paths.{id} to a local directory',
    zh: '重新执行 polaris init；离线环境可配 install.local-paths.{id} 指向本机目录',
  },
  depHintFallback: { en: 'Local fallback: {path}', zh: '本地保底载体：{path}' },
  openspecConsistent: {
    en: 'consistent with the current CLI (v{version})',
    zh: '与当前 CLI 一致 (v{version})',
  },
  openspecDrifted: {
    en: 'project skills were generated by v{baseline}, current CLI is v{actual}',
    zh: '项目技能由 v{baseline} 生成，当前 CLI 是 v{actual}',
  },
  openspecDriftHint: {
    en: 'polaris update --only openspec   # regenerate project skills with the current CLI',
    zh: 'polaris update --only openspec   # 用当前 CLI 重新生成项目技能',
  },
  installStateMissing: {
    en: 'not found (polaris init has not been run in this directory)',
    zh: '未找到（尚未在本目录执行过 polaris init）',
  },
  installStateNewerFormat: {
    en: 'format v{version} (this program supports up to v{supported}, consider upgrading polaris)',
    zh: 'format v{version}（本程序支持到 v{supported}，建议升级 polaris）',
  },
  installStateInvalid: {
    en: 'invalid JSON at {path}: {error}',
    zh: 'JSON 解析失败：{path}：{error}',
  },
  polarisSkillsOk: {
    en: '{count} platform(s) with Polaris skills',
    zh: '{count} 个平台已安装 Polaris 技能',
  },
  polarisSkillsMissing: {
    en: 'no Polaris skills detected on configured platforms',
    zh: '未在已配置平台上检测到 Polaris 技能',
  },
} as const satisfies Record<string, Record<Languages, string>>;

type DoctorMessageKey = keyof typeof MESSAGES;

/** 重要度 → 展示文案键 */
const REQUIREDNESS_LABEL_KEYS: Record<DependencyRequiredness, DoctorMessageKey> = {
  required: 'requiredLabel',
  recommended: 'recommendedLabel',
  optional: 'optionalLabel',
};

/** 用 {name} 占位符填充文案参数；未提供的占位符原样保留，便于发现漏参 */
function formatMessage(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (raw, key: string) =>
    key in params ? String(params[key]) : raw,
  );
}

/** 按语言取 doctor 文案并填充参数 */
function doctorMessage(
  lang: Languages,
  key: DoctorMessageKey,
  params: Record<string, string | number> = {},
): string {
  return formatMessage(MESSAGES[key][lang], params);
}

/**
 * 单项诊断级别。
 *
 * `skip` 表示「已知未装但按设计不需阻断」——用于 optional 依赖与不适用的检查项，
 * 与 `ok`（真的没问题）区分开，避免用户看到 ✓ 却读出 "not installed" 的矛盾。
 */
export type DiagnosticStatus = 'ok' | 'warn' | 'fail' | 'skip';

/** 单项诊断结果 */
export type DiagnosticItem = {
  name: string;
  status: DiagnosticStatus;
  message: string;
  /** 失败项的修复指引（多行，命令行层按缩进原样输出） */
  hint?: string;
};

function parseMinNodeVersion(range: string | undefined): number {
  if (!range) return 20;
  const match = range.match(/(\d+)/);
  return match ? parseInt(match[1], 10) : 20;
}

async function checkNode(lang: Languages): Promise<DiagnosticItem> {
  const minMajor = parseMinNodeVersion(engines?.node);
  const currentMajor = parseInt(process.version.slice(1).split('.')[0] ?? '0', 10);

  if (currentMajor >= minMajor) {
    return { name: 'node', status: 'ok', message: process.version };
  }

  return {
    name: 'node',
    status: 'fail',
    message: doctorMessage(lang, 'nodeRequires', { version: process.version, min: minMajor }),
  };
}

async function checkCommand(
  lang: Languages,
  name: string,
  command: string,
): Promise<DiagnosticItem> {
  const available = await isCommandAvailable(command);
  return {
    name,
    status: available ? 'ok' : 'fail',
    message: doctorMessage(lang, available ? 'commandAvailable' : 'commandNotFound'),
  };
}

/**
 * 缺失依赖的诊断级别（纯函数，便于单测覆盖分级规则）。
 *
 * - `required` 缺失 → fail（工作流跑不动，doctor 应以非零码退出）
 * - `recommended` 缺失 → warn（降级可用）
 * - `optional` 缺失 → skip（少个工具，按设计不阻断；用 skip 而非 ok，避免 ✓ 与 "not installed" 打架）
 */
export function dependencyDiagnosticStatus(
  requiredness: DependencyRequiredness,
  present: boolean,
): DiagnosticStatus {
  if (present) return 'ok';
  if (requiredness === 'required') return 'fail';
  if (requiredness === 'recommended') return 'warn';
  return 'skip';
}

/** 本地保底载体的可读路径，用于失败提示 */
function describeFallback(fallback: LocalFallback): string {
  return `~/.polaris/components/${fallback.relPath}`;
}

/**
 * 逐条检查依赖登记表里的外部组件。
 *
 * 判定与 init 完全同源（`probeDependency`），因此不会出现「init 说装好了、doctor 说没有」
 * 这类两套判据打架的情况。多平台场景下任一平台命中即视为已装。
 */
async function checkDependencies(
  projectPath: string,
  scope: InstallScope = 'project',
  lang: Languages = 'zh',
): Promise<DiagnosticItem[]> {
  const baseDir = getBaseDir(scope, projectPath);
  const detected = await detectPlatforms(projectPath);
  const skillsDirs = PLATFORMS.filter((platform) => detected.has(platform.id)).map((platform) =>
    getPlatformSkillsDir(platform, scope, baseDir),
  );
  const bundledSkillsDir = getBundledSkillsSourceDir();

  const items: DiagnosticItem[] = [];

  for (const spec of DEPENDENCIES) {
    let present = false;
    for (const skillsDir of skillsDirs) {
      if (await probeDependency(spec, { skillsDir, bundledSkillsDir })) {
        present = true;
        break;
      }
    }
    // 未检测到平台、或平台目录都没命中时，仍要能判定 CLI 类判据
    if (!present) {
      present = await probeDependency(spec, { bundledSkillsDir });
    }

    const status = dependencyDiagnosticStatus(spec.requiredness, present);
    const label = doctorMessage(lang, REQUIREDNESS_LABEL_KEYS[spec.requiredness]);

    if (present) {
      items.push({
        name: spec.id,
        status,
        message: doctorMessage(lang, 'depInstalled', { label }),
      });
      continue;
    }

    const hint =
      status === 'fail'
        ? [
            doctorMessage(lang, 'depHintReinstall', { id: spec.id }),
            spec.fallback
              ? doctorMessage(lang, 'depHintFallback', { path: describeFallback(spec.fallback) })
              : '',
          ]
            .filter(Boolean)
            .join('\n')
        : undefined;

    items.push({
      name: spec.id,
      status,
      message: `${doctorMessage(lang, 'depMissing', { label })}${
        status === 'skip' ? doctorMessage(lang, 'depMissingNoBlock') : ''
      }`,
      hint,
    });
  }

  return items;
}

/** 去掉 prerelease / build 元数据，只留 major.minor.patch 用于粗粒度比对 */
function normalizeVersion(version: string): string {
  return version.replace(/^v/, '').split('-')[0].split('+')[0];
}

/**
 * 判定「项目技能的生成基线」与「当前 CLI 版本」是否漂移（纯函数）。
 *
 * @param baseline 记录里的生成基线（上次 openspec init 用的 CLI 版本）
 * @param actual 当前 CLI 实测版本；探测失败传 null
 * @returns `null` 表示无法判定（任一侧不可比），调用方应跳过而非猜
 */
export function classifyOpenspecBaseline(
  baseline: string,
  actual: string | null,
): 'consistent' | 'drifted' | null {
  if (!isConcreteVersion(baseline)) return null;
  if (!actual || !isConcreteVersion(actual)) return null;
  return compareVersions(normalizeVersion(actual), normalizeVersion(baseline)) === 0
    ? 'consistent'
    : 'drifted';
}

/**
 * 检查项目里的 openspec 技能是否由当前 CLI 版本生成。
 *
 * 为什么只查 openspec：
 * - `openspec init` 的产物是**项目里的技能与命令文件**，不是指向全局 CLI 的引用。
 *   所以「项目技能的版本」等于上次 init 时那个 CLI 的版本；用户手动 `npm i -g` 升级 CLI 后，
 *   技能会静默过期，而 probe 只能回答「在不在」，回答不了「旧不旧」。
 * - superpowers 不做：npx 通道没有本地版本号，它的「版本」是上游 tag，比对必须联网，
 *   doctor 不该依赖网络。
 * - codegraph 不做：项目产物是可重建的索引，不是需要共享的资产，过期无副作用。
 *
 * 基线取 `.polaris/install-state.json` 的 `sources[].version`；实际版本直接读
 * `openspec --version`（`npm list -g` 在用户级安装时查不到）。任一侧不可比就不判断 ——
 * 宁可少报，不要误报。
 */
async function checkOpenspecBaseline(
  projectPath: string,
  lang: Languages,
): Promise<DiagnosticItem | null> {
  const state = await readInstallState(projectPath);
  const baseline = state?.sources.find((entry) => entry.id === 'openspec')?.version ?? '';
  if (!isConcreteVersion(baseline)) return null;

  const executable = resolveCliExecutable('openspec');
  // CLI 缺失已由 checkDependencies 报 fail，这里不重复报
  if (!executable) return null;

  const actual = extractSemver(readCliVersion(executable));
  const verdict = classifyOpenspecBaseline(baseline, actual);
  if (verdict === null) return null;

  if (verdict === 'consistent') {
    return {
      name: 'openspec-skills',
      status: 'ok',
      message: doctorMessage(lang, 'openspecConsistent', { version: baseline }),
    };
  }

  return {
    name: 'openspec-skills',
    status: 'warn',
    // verdict='drifted' 已保证 actual 是可比版本；`?? 'unknown'` 只为满足参数类型
    message: doctorMessage(lang, 'openspecDrifted', { baseline, actual: actual ?? 'unknown' }),
    hint: doctorMessage(lang, 'openspecDriftHint'),
  };
}

/**
 * 检查 `.polaris/install-state.json`（安装状态记录）。
 *
 * 只看文件是否可解析、格式版本是否为本程序认识的版本；不做语义判断——
 * 「某依赖是否可用」由 `checkDependencies` 现查，比读记录更可靠。
 */
async function checkInstallState(projectPath: string, lang: Languages): Promise<DiagnosticItem> {
  const statePath = getInstallStatePath(projectPath);
  if (!(await fileExists(statePath))) {
    return {
      name: 'install-state.json',
      status: 'warn',
      message: doctorMessage(lang, 'installStateMissing'),
    };
  }

  try {
    const raw = await readJsonObjectOrEmpty(statePath);
    const formatVersion = (raw as { version?: unknown }).version;
    if (typeof formatVersion === 'number' && formatVersion > INSTALL_STATE_FORMAT_VERSION) {
      return {
        name: 'install-state.json',
        status: 'warn',
        message: doctorMessage(lang, 'installStateNewerFormat', {
          version: formatVersion,
          supported: INSTALL_STATE_FORMAT_VERSION,
        }),
      };
    }
    return { name: 'install-state.json', status: 'ok', message: statePath };
  } catch (error) {
    return {
      name: 'install-state.json',
      status: 'fail',
      message: doctorMessage(lang, 'installStateInvalid', {
        path: statePath,
        error: (error as Error).message,
      }),
    };
  }
}

async function checkPolarisSkills(
  projectPath: string,
  scope: InstallScope = 'project',
  lang: Languages = 'zh',
): Promise<DiagnosticItem> {
  const baseDir = getBaseDir(scope, projectPath);
  const detected = await detectPlatforms(projectPath);
  let installedCount = 0;

  for (const platform of PLATFORMS) {
    if (!detected.has(platform.id)) {
      continue;
    }
    const skillsBaseDir = getPlatformSkillsDir(platform, scope, baseDir);
    if (await hasSkills(skillsBaseDir, 'polaris')) {
      installedCount++;
    }
  }

  if (installedCount > 0) {
    return {
      name: 'polaris-skills',
      status: 'ok',
      message: doctorMessage(lang, 'polarisSkillsOk', { count: installedCount }),
    };
  }

  return {
    name: 'polaris-skills',
    status: 'warn',
    message: doctorMessage(lang, 'polarisSkillsMissing'),
  };
}

/**
 * 运行环境诊断。
 *
 * @param lang 输出语言；CLI 按 `.polaris/config.yaml` 的 `language` 传入（init 时选择），
 *             与 `polaris update` 的取值约定一致（config 缺失时落 zh）
 */
export async function runDiagnostics(
  projectPath: string,
  scope: InstallScope = 'project',
  lang: Languages = 'zh',
): Promise<DiagnosticItem[]> {
  const checks: DiagnosticItem[] = [];

  checks.push(await checkNode(lang));
  // git 不是依赖表里的组件，而是 init / 在线通道的运行时前提（缺失不阻断，只提示）
  checks.push(await checkCommand(lang, 'git', 'git'));
  // 依赖逐条检查：openspec / superpowers / codegraph / archify / diagram-design
  checks.push(...(await checkDependencies(projectPath, scope, lang)));
  // 基线漂移：项目技能是否由当前 CLI 生成（只有能判定时才有该项）
  const baseline = await checkOpenspecBaseline(projectPath, lang);
  if (baseline) checks.push(baseline);
  checks.push(await checkInstallState(projectPath, lang));
  checks.push(await checkPolarisSkills(projectPath, scope, lang));

  return checks;
}

/** 是否存在 fail 级别诊断项 */
export function hasDiagnosticFailure(checks: DiagnosticItem[]): boolean {
  return checks.some((item) => item.status === 'fail');
}
